import Foundation
import LiteCore

func runOrderingChecks(root: URL, base: Date) throws {
    try runDefaultOrderingChecks(root: root, base: base)
    try runActivityPriorityChecks(root: root, base: base)
    let url = root.appendingPathComponent("ordering.sqlite")
    let store = try TaskStore(url: url)
    let a = try store.createTask(title: "A", at: base)
    let hidden = try store.createTask(title: "已完成", at: base)
    let b = try store.createTask(title: "B", at: base)
    let c = try store.createTask(title: "C", at: base)
    let a1 = try store.createTask(title: "A1", parentID: a, at: base)
    let a2 = try store.createTask(title: "A2", parentID: a, at: base)
    check("default-task-order-is-newest-first-with-id-tiebreak", try store.snapshot().rootTasks.map(\.id) == [c, b, hidden, a])
    check("default-subtask-order-is-newest-first", try store.snapshot().children(of: a).map(\.id) == [a2, a1])
    // Arrange a manual baseline, including the hidden completed task.
    try store.moveTask(a, relativeTo: c, placement: .before)
    try store.moveTask(hidden, relativeTo: c, placement: .before)
    try store.moveTask(b, relativeTo: c, placement: .before)
    try store.setStatus(hidden, .done)
    try store.moveTask(c, relativeTo: a, placement: .before)
    check("task-drag-moves-up", try store.snapshot().rootTasks.map(\.id) == [c, a, hidden, b])
    try store.moveTask(c, relativeTo: b, placement: .after)
    check("task-drag-moves-down-with-hidden-task-intact", try store.snapshot().rootTasks.map(\.id) == [a, hidden, b, c])
    try store.moveTask(a1, relativeTo: a2, placement: .before)
    try store.moveTask(a2, relativeTo: a1, placement: .before)
    try store.moveTask(a, relativeTo: c, placement: .after)
    check("task-drag-carries-children-as-group", try store.snapshot().outlineTasks.map(\.id) == [hidden, b, c, a, a2, a1])
    check("task-order-survives-reopen", try TaskStore(url: url).snapshot() == store.snapshot())
    check("task-drag-rejects-reparenting", rejected { try store.moveTask(a1, relativeTo: b, placement: .after) })
    check("task-drag-rejects-missing-target", rejected { try store.moveTask(a, relativeTo: 99999, placement: .before) })
    let beforeSelf = try store.snapshot()
    try store.moveTask(a, relativeTo: a, placement: .after)
    check("task-drag-self-is-no-op", try store.snapshot() == beforeSelf)
    let appended = try store.createTask(title: "末尾新任务")
    let childAppended = try store.createTask(title: "末尾新子任务", parentID: a)
    check("new-task-appends-to-manual-order", try store.snapshot().rootTasks.map(\.id) == [hidden, b, c, a, appended])
    check("new-subtask-appends-to-manual-order", try store.snapshot().children(of: a).map(\.id) == [a2, a1, childAppended])
    try store.setStatus(a, .done); try store.renameTask(c, title: "重命名")
    check("task-status-and-title-keep-order", try store.snapshot().rootTasks.map(\.id) == [hidden, b, c, a, appended])
    let one = ObservedSession(id: "one", title: "One", status: .running, updatedAt: base)
    let two = ObservedSession(id: "two", title: "Two", updatedAt: base)
    let three = ObservedSession(id: "three", title: "Three", updatedAt: base)
    try store.attach(one, to: a, at: base)
    try store.attach(two, to: a, at: base.addingTimeInterval(1))
    try store.attach(three, to: a, at: base.addingTimeInterval(2))
    check("default-session-order-uses-newest-binding-for-equal-updates", try store.snapshot().sessions(for: a).map(\.id) == ["three", "two", "one"])
    try store.moveSession("one", relativeTo: "three", in: a, placement: .before)
    try store.moveSession("three", relativeTo: "one", in: a, placement: .before)
    check("session-drag-moves-up", try store.snapshot().sessions(for: a).map(\.id) == ["three", "one", "two"])
    try store.moveSession("three", relativeTo: "two", in: a, placement: .after)
    check("session-drag-moves-down", try store.snapshot().sessions(for: a).map(\.id) == ["one", "two", "three"])
    try store.moveSession("two", relativeTo: "one", in: a, placement: .before)
    try store.attach(one, to: a, at: base.addingTimeInterval(100))
    try store.reconcile([ObservedSession(id: "one", title: "运行完成", status: .completed, updatedAt: base.addingTimeInterval(200), taskNumber: a, commandAt: base.addingTimeInterval(200))])
    check("session-activity-overrides-manual-order", try store.snapshot().sessions(for: a).map(\.id) == ["one", "two", "three"])
    check("session-order-survives-reopen", try TaskStore(url: url).snapshot().sessions(for: a).map(\.id) == ["one", "two", "three"])
    let four = ObservedSession(id: "four", title: "Four", updatedAt: base.addingTimeInterval(300))
    try store.attach(four, to: a)
    check("new-active-session-precedes-manual-order", try store.snapshot().sessions(for: a).map(\.id) == ["four", "one", "two", "three"])
    try store.attach(two, to: b)
    check("session-drag-rejects-other-task", rejected { try store.moveSession("two", relativeTo: "one", in: a, placement: .before) })
    check("session-invalid-drag-keeps-associations", try store.snapshot().sessions(for: b).map(\.id) == ["two"])
    try store.attach(one, to: b)
    check("session-transfer-follows-destination-default-time-order", try store.snapshot().sessions(for: b).map(\.id) == ["one", "two"])
    try store.detach("two"); try store.attach(two, to: b)
    check("session-reattach-keeps-default-time-order", try store.snapshot().sessions(for: b).map(\.id) == ["one", "two"])
    check("session-drag-rejects-unbound", rejected { try store.moveSession("missing", relativeTo: "one", in: b, placement: .before) })

    // Pre-drag databases adopt the new default while retaining IDs, badges and links.
    let legacy = root.appendingPathComponent("ordering-v3.sqlite")
    try sql(legacy, """
    CREATE TABLE tasks(id INTEGER PRIMARY KEY AUTOINCREMENT,title TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'todo',created_at REAL NOT NULL,parent_id INTEGER REFERENCES tasks(id) ON DELETE SET NULL,unread_completion INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE sessions(id TEXT PRIMARY KEY,task_id INTEGER REFERENCES tasks(id),title TEXT NOT NULL,status TEXT NOT NULL,updated_at REAL NOT NULL,bound_at REAL NOT NULL);
    INSERT INTO tasks VALUES(7,'原主任务','done',1,NULL,1),(9,'原子任务','doing',2,7,1),(12,'原另一主任务','todo',3,NULL,0);
    INSERT INTO sessions VALUES('z',7,'First','running',3,1),('b',7,'Third','completed',3,2),('a',7,'Second','idle',3,2);
    PRAGMA application_id=1129598036; PRAGMA user_version=3;
    """)
    let upgraded = try TaskStore(url: legacy)
    check("schema-three-migration-adopts-default-task-order", try upgraded.snapshot().outlineTasks.map(\.id) == [12, 7, 9])
    check("schema-three-migration-adopts-default-session-order", try upgraded.snapshot().sessions(for: 7).map(\.id) == ["b", "a", "z"])
    check("schema-three-migration-preserves-badges-and-status", try upgraded.snapshot().tasks.first { $0.id == 7 }?.status == .done && upgraded.snapshot().tasks.first { $0.id == 7 }?.hasUnreadCompletion == true)
    check("schema-three-migration-keeps-next-task-id", try upgraded.createTask(title: "下一任务") == 13)
    check("schema-four-reopen-idempotent", try TaskStore(url: legacy).snapshot() == upgraded.snapshot())
}

private func runDefaultOrderingChecks(root: URL, base: Date) throws {
    let url = root.appendingPathComponent("time-order.sqlite")
    let store = try TaskStore(url: url)
    let newest = try store.createTask(title: "最新", at: base.addingTimeInterval(20))
    let oldest = try store.createTask(title: "最早", at: base)
    let middle = try store.createTask(title: "中间", at: base.addingTimeInterval(10))
    check("default-task-order-uses-time-rather-than-insertion", try store.snapshot().rootTasks.map(\.id) == [newest, middle, oldest])
    try store.moveTask(middle, relativeTo: newest, placement: .after)
    try store.moveTask(oldest, relativeTo: oldest, placement: .before)
    check("no-op-task-drag-does-not-freeze-default", try scalar(url, "SELECT count(*) FROM manual_ordering") == 0)
    try store.renameTask(oldest, title: "改标题"); try store.setStatus(oldest, .doing)
    check("editing-task-does-not-change-creation-order", try store.snapshot().rootTasks.map(\.id) == [newest, middle, oldest])
    let recent = try store.createTask(title: "新任务", at: base.addingTimeInterval(30))
    check("new-default-task-goes-to-top", try store.snapshot().rootTasks.first?.id == recent)
    try store.moveTask(oldest, relativeTo: middle, placement: .before)
    check("first-drag-preserves-other-visible-task-positions", try store.snapshot().rootTasks.map(\.id) == [recent, newest, oldest, middle])
    let child1 = try store.createTask(title: "子任务一", parentID: newest, at: base)
    let child2 = try store.createTask(title: "子任务二", parentID: newest, at: base.addingTimeInterval(1))
    check("manual-root-does-not-freeze-child-default", try store.snapshot().children(of: newest).map(\.id) == [child2, child1])
    try store.moveTask(child1, relativeTo: child2, placement: .before)
    let otherChild1 = try store.createTask(title: "另一组一", parentID: middle, at: base)
    let otherChild2 = try store.createTask(title: "另一组二", parentID: middle, at: base.addingTimeInterval(1))
    check("manual-child-order-is-local-to-parent", try store.snapshot().children(of: middle).map(\.id) == [otherChild2, otherChild1])
    let one = ObservedSession(id: "a", title: "A", updatedAt: base.addingTimeInterval(10))
    let two = ObservedSession(id: "z", title: "Z", updatedAt: base)
    try store.attach(one, to: newest, at: base)
    try store.attach(two, to: newest, at: base.addingTimeInterval(100))
    check("default-session-order-uses-update-before-binding-and-id", try store.snapshot().sessions(for: newest).map(\.id) == ["a", "z"])
    try store.moveSession("z", relativeTo: "a", in: newest, placement: .after)
    check("no-op-session-drag-does-not-freeze-default", try scalar(url, "SELECT count(*) FROM manual_ordering WHERE scope LIKE 'sessions:%'") == 0)
    var updated = two; updated.updatedAt = base.addingTimeInterval(20)
    try store.reconcile([updated, one])
    check("updated-default-session-rises-to-top", try store.snapshot().sessions(for: newest).map(\.id) == ["z", "a"])
    try store.reconcile([two])
    check("stale-session-update-does-not-change-order", try store.snapshot().sessions(for: newest).map(\.id) == ["z", "a"])
    let fresh = ObservedSession(id: "fresh", title: "新会话", updatedAt: base.addingTimeInterval(30))
    try store.attach(fresh, to: newest, at: base)
    check("new-default-session-goes-to-top", try store.snapshot().sessions(for: newest).map(\.id) == ["fresh", "z", "a"])
    try store.moveSession("a", relativeTo: "z", in: newest, placement: .before)
    check("first-session-drag-preserves-other-visible-positions", try store.snapshot().sessions(for: newest).map(\.id) == ["fresh", "a", "z"])
    updated.updatedAt = base.addingTimeInterval(40)
    try store.reconcile([updated])
    check("updated-manual-session-rises-to-top", try store.snapshot().sessions(for: newest).map(\.id) == ["z", "fresh", "a"])
    try store.attach(ObservedSession(id: "other-old", title: "旧", updatedAt: base), to: middle)
    try store.attach(ObservedSession(id: "other-new", title: "新", updatedAt: base.addingTimeInterval(1)), to: middle)
    check("manual-session-order-is-local-to-task", try store.snapshot().sessions(for: middle).map(\.id) == ["other-new", "other-old"])
    check("default-and-manual-modes-survive-reopen", try TaskStore(url: url).snapshot() == store.snapshot())

    // Simulate a v5 database with both untouched and reordered groups.
    let legacyURL = root.appendingPathComponent("time-order-v5.sqlite")
    let legacy = try TaskStore(url: legacyURL)
    let parent = try legacy.createTask(title: "父", at: base)
    let later = try legacy.createTask(title: "后建", at: base.addingTimeInterval(1))
    let child = try legacy.createTask(title: "子一", parentID: parent, at: base.addingTimeInterval(10))
    let childLater = try legacy.createTask(title: "子二", parentID: parent, at: base.addingTimeInterval(1))
    try legacy.attach(ObservedSession(id: "legacy-a", title: "A", updatedAt: base), to: parent, at: base)
    try legacy.attach(ObservedSession(id: "legacy-b", title: "B", updatedAt: base.addingTimeInterval(1)), to: parent, at: base.addingTimeInterval(1))
    try legacy.attach(ObservedSession(id: "manual-a", title: "A", updatedAt: base.addingTimeInterval(10)), to: later, at: base)
    try legacy.attach(ObservedSession(id: "manual-b", title: "B", updatedAt: base), to: later, at: base.addingTimeInterval(1))
    try sql(legacyURL, """
    UPDATE tasks SET sort_order=id;
    UPDATE tasks SET sort_order=-1 WHERE id=\(childLater);
    UPDATE sessions SET sort_order=CASE id WHEN 'legacy-a' THEN 0 WHEN 'legacy-b' THEN 1 WHEN 'manual-b' THEN 0 ELSE 1 END;
    DROP TABLE manual_ordering;
    ALTER TABLE sessions DROP COLUMN activity_order;
    PRAGMA user_version=5;
    """)
    let upgraded = try TaskStore(url: legacyURL)
    check("schema-five-default-roots-switch-to-time-order", try upgraded.snapshot().rootTasks.map(\.id) == [later, parent])
    check("schema-five-manual-child-order-is-preserved", try upgraded.snapshot().children(of: parent).map(\.id) == [childLater, child])
    check("schema-five-default-sessions-switch-to-time-order", try upgraded.snapshot().sessions(for: parent).map(\.id) == ["legacy-b", "legacy-a"])
    check("schema-five-manual-sessions-override-time-order", try upgraded.snapshot().sessions(for: later).map(\.id) == ["manual-b", "manual-a"])
    check("schema-seven-reopen-does-not-reinfer-manual-modes", try TaskStore(url: legacyURL).snapshot() == upgraded.snapshot())
}

private func runActivityPriorityChecks(root: URL, base: Date) throws {
    let url = root.appendingPathComponent("activity-priority.sqlite")
    let store = try TaskStore(url: url)
    let task = try store.createTask(title: "活跃排序", at: base)
    var a = ObservedSession(id: "a", title: "A", updatedAt: base.addingTimeInterval(1))
    var b = ObservedSession(id: "b", title: "B", updatedAt: base.addingTimeInterval(2))
    var c = ObservedSession(id: "c", title: "C", updatedAt: base.addingTimeInterval(3))
    for session in [a,b,c] { try store.attach(session, to: task, at: base) }
    try store.moveSession("c", relativeTo: "a", in: task, placement: .after)
    check("recent-session-can-be-manually-moved-to-bottom", try store.snapshot().sessions(for: task).map(\.id) == ["b", "a", "c"])
    try store.reconcile([c,b,a])
    check("repeated-poll-keeps-manual-session-order", try store.snapshot().sessions(for: task).map(\.id) == ["b", "a", "c"])
    var stale = c; stale.updatedAt = base.addingTimeInterval(2)
    try store.reconcile([stale]); try store.attach(c, to: task, at: base.addingTimeInterval(100))
    check("old-activity-and-rebinding-do-not-promote-session", try store.snapshot().sessions(for: task).map(\.id) == ["b", "a", "c"])
    let reopened = try TaskStore(url: url)
    c.updatedAt = base.addingTimeInterval(4)
    try reopened.reconcile([c])
    check("bottom-session-new-activity-promotes-after-restart", try reopened.snapshot().sessions(for: task).map(\.id) == ["c", "b", "a"])
    check("activity-priority-survives-restart", try TaskStore(url: url).snapshot() == reopened.snapshot())
    try store.moveSession("c", relativeTo: "a", in: task, placement: .after)
    try store.reconcile([c])
    check("another-drag-clears-previous-activity-priority", try store.snapshot().sessions(for: task).map(\.id) == ["b", "a", "c"])
    b.updatedAt = base.addingTimeInterval(6); c.updatedAt = base.addingTimeInterval(5)
    try store.reconcile([b,c])
    check("batch-activity-order-follows-time-not-arrival", try store.snapshot().sessions(for: task).map(\.id) == ["b", "c", "a"])
    a.updatedAt = base.addingTimeInterval(7); try store.reconcile([a])
    check("newest-activity-overtakes-other-active-sessions", try store.snapshot().sessions(for: task).map(\.id) == ["a", "b", "c"])
    try store.moveSession("a", relativeTo: "c", in: task, placement: .after)
    let d = ObservedSession(id: "d", title: "D", updatedAt: base.addingTimeInterval(8))
    try store.attach(d, to: task)
    check("new-session-activity-overtakes-saved-manual-order", try store.snapshot().sessions(for: task).map(\.id) == ["d", "b", "c", "a"])

    // A real schema-6 layout keeps saved manual ranks until activity advances.
    let legacyURL = root.appendingPathComponent("activity-priority-v6.sqlite")
    let legacy = try TaskStore(url: legacyURL)
    let legacyTask = try legacy.createTask(title: "旧库", at: base)
    try legacy.attach(a, to: legacyTask); try legacy.attach(b, to: legacyTask)
    try legacy.moveSession("a", relativeTo: "b", in: legacyTask, placement: .after)
    try sql(legacyURL, "ALTER TABLE sessions DROP COLUMN activity_order; PRAGMA user_version=6;")
    let migrated = try TaskStore(url: legacyURL)
    check("schema-six-migration-keeps-manual-session-ranks", try migrated.snapshot().sessions(for: legacyTask).map(\.id) == ["b", "a"])
    try migrated.reconcile([a,b])
    check("schema-six-migration-does-not-treat-history-as-new-activity", try migrated.snapshot().sessions(for: legacyTask).map(\.id) == ["b", "a"])
    a.updatedAt = base.addingTimeInterval(9); try migrated.reconcile([a])
    check("schema-six-migration-allows-new-activity-to-override-ranks", try migrated.snapshot().sessions(for: legacyTask).map(\.id) == ["a", "b"])
    check("schema-six-upgrades-to-seven", try scalar(legacyURL, "PRAGMA user_version") == 7)
}
